function slugEmail(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '.')
      .replace(/(^\.|\.$)/g, '') + '@kopituju.id'
  );
}

function buildScores(pattern: number[]): Record<string, number | null> {
  const scores: Record<string, number | null> = {};
  DEFAULT_INDICATORS.forEach((ind, idx) => {
    scores[ind.code] = pattern[idx % pattern.length];
  });
  return scores;
}

